// pnpm db:migrate:new <name>
// Creates a migration for BOTH providers by diffing the last snapshot of schema.prisma against the current one
// (no live database needed for SQLite), and regenerates src/migrations.generated.ts which embeds the SQL
// into the application so migrations run on customer machines without the Prisma CLI.
import fs from "node:fs";
import path from "node:path";
import { prisma, read, root, toPostgres, write } from "./lib.mjs";

const embedOnly = process.argv.includes("--embed-only");
const name = (process.argv[2] ?? "").replace(/[^a-z0-9_]+/gi, "_").toLowerCase();
if (!name && !embedOnly) {
  console.error("usage: pnpm db:migrate:new <name>");
  process.exit(1);
}

if (!embedOnly) {
  const snapDir = path.join(root, "migrations", "_snapshot");
  const snap = path.join(snapDir, "schema.prisma");
  const tmpFromPg = path.join(snapDir, "from.postgres.prisma");
  const tmpToPg = path.join(snapDir, "to.postgres.prisma");
  fs.mkdirSync(snapDir, { recursive: true });
  const current = read("prisma/schema.prisma");
  fs.writeFileSync(tmpToPg, toPostgres(current));
  const hasSnap = fs.existsSync(snap);
  if (hasSnap) fs.writeFileSync(tmpFromPg, toPostgres(fs.readFileSync(snap, "utf8")));
  const from = (pg) => (hasSnap ? ["--from-schema-datamodel", pg ? tmpFromPg : snap] : ["--from-empty"]);
  try {
    const sqlite = prisma(["migrate", "diff", ...from(false), "--to-schema-datamodel", "prisma/schema.prisma", "--script", "--config", "prisma.sqlite.config.ts"]);
    const pg = prisma(["migrate", "diff", ...from(true), "--to-schema-datamodel", tmpToPg, "--script", "--config", "prisma.postgres.config.ts"]);
    if (/This is an empty migration/.test(sqlite) || !sqlite.trim()) {
      console.log("No schema changes.");
    } else {
      const stamp = new Date().toISOString().replace(/\D/g, "").slice(0, 14);
      const id = `${stamp}_${name}`;
      write(`migrations/sqlite/${id}/migration.sql`, sqlite);
      write(`migrations/postgres/${id}/migration.sql`, pg);
      fs.writeFileSync(snap, current);
      console.log(`Created migration ${id}`);
    }
  } finally {
    fs.rmSync(tmpFromPg, { force: true });
    fs.rmSync(tmpToPg, { force: true });
  }
}

// embed
const embed = (provider) =>
  fs.existsSync(path.join(root, "migrations", provider))
    ? fs
        .readdirSync(path.join(root, "migrations", provider))
        .filter((d) => /^\d{14}_/.test(d))
        .sort()
        .map((d) => ({ id: d, sql: fs.readFileSync(path.join(root, "migrations", provider, d, "migration.sql"), "utf8").replace(/\r\n/g, "\n") }))
    : [];
const body = `// GENERATED by scripts/new-migration.mjs — do not edit.\nexport interface EmbeddedMigration { id: string; sql: string }\nexport const SQLITE_MIGRATIONS: EmbeddedMigration[] = ${JSON.stringify(embed("sqlite"), null, 1)};\nexport const POSTGRES_MIGRATIONS: EmbeddedMigration[] = ${JSON.stringify(embed("postgres"), null, 1)};\n`;
write("src/migrations.generated.ts", body);
console.log("Embedded migrations updated");
